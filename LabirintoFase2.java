    private boolean faseCompleta = false;
    
    public LabirintoFase2()
    {    
        super(25, 20, 40);
        gerarCenario();
    }
    
    private void gerarCenario() {
        for (int linha = 0; linha < mapa.length; linha++){
            for (int coluna = 0; coluna < mapa[linha].length; coluna++) { 
                int bloco = mapa[linha][coluna];
                
                if (bloco == 1) {
                    addObject(new Parede(), coluna, linha);
                }
                else if (bloco == 2) {
                    addObject(new Teseu(), coluna, linha);
                }
                else if (bloco == 3) {
                    addObject(new Minotauro(), coluna, linha);
                }
            }
        }
    }
    
    public void verificarSaida(Teseu teseu) {
        if (!faseCompleta && teseu.getX() == 24 && teseu.getY() == 19) {
            faseCompleta = true;
            avancarParaProximaFase(teseu);
        }
    }
    
    private void avancarParaProximaFase(Teseu teseu) {
        try {
            Greenfoot.playSound("NextFase.wav");
        } catch(Exception e) {}
        
        mostrarMensagem("Fase 2 Completa! Entrando na Fase 3...");
        Greenfoot.delay(60);
        Greenfoot.stop();
    }
    
    private void mostrarMensagem(String texto) {
        Label label = new Label(texto, 30);
        addObject(label, getWidth() / 2, getHeight() / 2);
    }
